"""
Generate `assets/starsim-theme.html`, the head snippet that makes the docs site match the
rest of the Starsim documentation.

Dev/CI tool -- NOT part of the installed package.

`great-docs.yml` pulls the generated file in through `include_in_header`. It lives in
`assets/` because Quarto resolves a `file:` include relative to the build directory, and
`assets/` is one of the few directories great-docs mirrors there verbatim. It carries three
things that the great-docs configuration cannot express on its own:

1. **The full site navigation in the left sidebar of every page.** great-docs gives each
   navbar section its own sidebar containing only that section's pages. The Starsim docs
   instead put the whole page list in the sidebar and use the navbar for the top level,
   which is easier to navigate and is what this restores. Reference pages keep their own
   API sidebar, as they do in the Starsim docs.
2. **A Starsim-style footer**: the Gates Foundation attribution, the Privacy and Terms
   links, and the icon row.
3. **A stylesheet fix** so that matplotlib figures scale to the content column instead of
   being clipped by it.

The navigation is generated from the section directories rather than hand-written, and
`--check` verifies that the committed file still matches them, so a page added or renamed
without regenerating is caught by the test suite rather than by a reader.

Usage:

```bash
python scripts/build_docs_theme.py            # -> assets/starsim-theme.html
python scripts/build_docs_theme.py --check    # verify it is up to date; write nothing
```
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DOCS = REPO / "docs"
OUT = REPO / "assets" / "starsim-theme.html"

# Section title -> directory, in navbar order. Must match `sections:` in great-docs.yml.
SECTIONS = [
    ("Getting started", "start"),
    ("The data", "data"),
    ("Internals", "internals"),
]

# The footer, matching https://docs.starsim.org and https://starsim.org/tbsim.
COPYRIGHT = ("&copy; 2023&ndash;2026, Gates Foundation. All rights reserved. "
             '<a href="https://www.gatesfoundation.org/Privacy-and-Cookies-Notice">'
             "Privacy and Cookies Notice</a> | "
             '<a href="https://www.gatesfoundation.org/Terms-of-Use">Terms of Use</a>')
LINKS = [
    ("github", "https://github.com/starsimhub/starsim_data", "GitHub"),
    ("envelope-at-fill", "mailto:info@starsim.org", "Email"),
    ("slack", "https://starsim-idm.slack.com", "Slack"),
    ("globe", "https://starsim.org", "Starsim"),
]


def page_title(path):
    """Return a page's `title:` from its YAML frontmatter."""
    text = path.read_text(encoding="utf-8")
    match = re.search(r'^title:\s*"?(.+?)"?\s*$', text, flags=re.M)
    if not match:
        raise SystemExit(f"{path} has no title in its frontmatter")
    return match.group(1)


def navigation():
    """Return `[{title, pages: [{href, title}]}]` for the section directories."""
    out = []
    for title, folder in SECTIONS:
        directory = DOCS / folder
        if not directory.is_dir():
            raise SystemExit(f"no such section directory: {directory}")
        pages = []
        for path in sorted(directory.glob("*.qmd")):
            # great-docs strips the ordering prefix from the URL.
            slug = re.sub(r"^\d+-", "", path.stem)
            pages.append(dict(href=f"docs/{folder}/{slug}.html", title=page_title(path)))
        if not pages:
            raise SystemExit(f"section {title!r} has no pages")
        out.append(dict(title=title, pages=pages))
    return out


def render(nav):
    """Return the head snippet: the figure fix, the sidebar script and the footer."""
    # Joined without newlines: this is interpolated into a JavaScript string literal,
    # and a raw newline inside one is a syntax error.
    icons = "".join(
        f'<a href="{href}" title="{label}" aria-label="{label}">'
        f'<i class="bi bi-{icon}"></i></a>' for icon, href, label in LINKS)
    return f"""<!--
  GENERATED by scripts/build_docs_theme.py -- do not edit by hand.
  Regenerate with: python scripts/build_docs_theme.py
-->
<style>
  /* Matplotlib figures are emitted at their native pixel size, which for a multi-panel
     figure is wider than the content column. !important because the theme stylesheet
     loads after this block and sets max-width: none. */
  img.figure-img,
  .cell-output-display img {{
    max-width: 100% !important;
    height: auto !important;
  }}
  /* Section headings in the rebuilt sidebar, styled like great-docs' own. */
  .gd-nav-heading {{
    font-size: 0.8rem;
    font-weight: 600;
    letter-spacing: 0.04em;
    text-transform: uppercase;
    opacity: 0.65;
    margin: 1.1rem 0 0.3rem 0;
  }}
  .gd-nav-heading:first-child {{ margin-top: 0.25rem; }}
  /* Footer: centred text, icons on the right, matching the other Starsim sites. */
  footer.footer .nav-footer {{ display: flex; align-items: center; gap: 1rem; }}
  footer.footer .nav-footer-center {{ flex: 1 1 auto; }}
  footer.footer .nav-footer-center p {{ text-align: center !important; margin: 0; }}
  footer.footer .nav-footer-right {{ flex: 0 0 auto; display: flex; gap: 0.75rem; font-size: 1.1rem; }}
  @media (max-width: 700px) {{
    footer.footer .nav-footer {{ flex-direction: column; }}
  }}
</style>
<script>
(function () {{
  var NAV = {json.dumps(nav, indent=2)};

  function siteRoot() {{
    // The navbar brand always points at the site root, which is the only reliable way to
    // build absolute URLs when the site may be served from a subdirectory.
    var brand = document.querySelector('.navbar-brand, a.navbar-brand');
    if (!brand) return null;
    return brand.href.replace(/index\\.html?$/, '').replace(/\\/?$/, '/');
  }}

  function buildSidebar() {{
    var container = document.querySelector('#quarto-sidebar .sidebar-menu-container');
    var root = siteRoot();
    if (!container || !root) return;

    // Only take over the sidebar on pages that are part of the guide; Reference pages
    // keep their own API navigation.
    var here = window.location.pathname.replace(/\\/$/, '');
    var mine = NAV.some(function (s) {{
      return s.pages.some(function (p) {{ return new URL(p.href, root).pathname === here; }});
    }});
    if (!mine) return;

    var html = '';
    NAV.forEach(function (section) {{
      html += '<div class="gd-nav-heading">' + section.title + '</div>';
      html += '<ul class="list-unstyled mt-1">';
      section.pages.forEach(function (page) {{
        var url = new URL(page.href, root);
        var active = url.pathname === here ? ' active' : '';
        html += '<li class="sidebar-item"><div class="sidebar-item-container">' +
                '<a href="' + url.href + '" class="sidebar-item-text sidebar-link' + active +
                '"><span class="menu-text">' + page.title + '</span></a></div></li>';
      }});
      html += '</ul>';
    }});
    container.innerHTML = html;
  }}

  function buildFooter() {{
    var footer = document.querySelector('footer.footer .nav-footer');
    if (!footer) return;
    footer.innerHTML =
      '<div class="nav-footer-center"><p>{COPYRIGHT}</p></div>' +
      '<div class="nav-footer-right">{icons}</div>';
  }}

  function apply() {{ buildSidebar(); buildFooter(); }}

  if (document.readyState === 'loading') {{
    document.addEventListener('DOMContentLoaded', apply);
  }} else {{
    apply();
  }}
}})();
</script>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="verify the committed file is up to date; write nothing")
    args = parser.parse_args()

    nav = navigation()
    content = render(nav)
    pages = sum(len(s["pages"]) for s in nav)

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != content:
            raise SystemExit(f"{OUT.relative_to(REPO)} is out of date; regenerate it with:\n"
                             f"  python scripts/build_docs_theme.py")
        print(f"{OUT.relative_to(REPO)} is up to date "
              f"({len(nav)} sections, {pages} pages).")
        return

    OUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(REPO)}: {len(nav)} sections, {pages} pages")
    for section in nav:
        print(f"  {section['title']}: " +
              ", ".join(p["title"] for p in section["pages"]))


if __name__ == "__main__":
    sys.exit(main())
